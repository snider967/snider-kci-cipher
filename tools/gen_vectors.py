"""Generate tests/kat_vectors.h from the Python reference sketch (tools/kci_ref.py).

These are *provisional* vectors: the C portable path must agree with them (two independent implementations).
The ChaCha-mode stream vector is also checked against OpenSSL's chacha20 when `openssl` is on PATH.

Run from the repo root:  python3 -I tools/gen_vectors.py
"""
import hashlib, hmac, os, random, shutil, struct, subprocess, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
import kci_ref as K  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tests', 'kat_vectors.h')

def carr(b):
    return '{' + ','.join(f'0x{x:02x}' for x in b) + '}'

def stream(key_obj_block, ctr0, nonce, n):
    ks = b''; c = ctr0
    while len(ks) < n:
        ks += key_obj_block(c, nonce); c += 1
    return ks[:n]

def chacha_block(key, ctr, nonce):
    return struct.pack('<16I', *K.core(K.CHACHA_CONST, key, ctr, nonce, [(16, 12, 8, 7)] * 20, [0] * 20))

def main():
    L = []
    w = L.append
    w('/* GENERATED by tools/gen_vectors.py from tools/kci_ref.py (spec v0.2). Do not edit by hand. */')
    w('#ifndef KCI_KAT_VECTORS_H\n#define KCI_KAT_VECTORS_H\n#include <stdint.h>\n')

    # tables (C must match the Python FROZEN / PACKED)
    w('static const uint8_t kat_loop_rot[8][4] = {' + ','.join('{' + ','.join(map(str, p)) + '}' for p in K.LOOP_ROT) + '};')
    w('static const uint32_t kat_loop_packed[8] = {' + ','.join(f'0x{p:08x}u' for p in K.PACKED) + '};\n')

    # 1. block KATs with their decks: fixed key, then deterministic pseudo-random keys
    rnd = random.Random(20261127)
    keys = [bytes(range(32))] + [bytes(rnd.getrandbits(8) for _ in range(32)) for _ in range(5)]
    w('struct kat_block { uint8_t key[32]; uint8_t nonce[12]; uint32_t ctr; uint8_t deck[20]; uint8_t out[64]; };')
    w('static const struct kat_block kat_blocks[] = {')
    for i, key in enumerate(keys):
        nonce = bytes.fromhex('000000090000004a00000000') if i == 0 else bytes(rnd.getrandbits(8) for _ in range(12))
        ctr = 1 if i == 0 else rnd.choice([0, 1, 2, 0x7fffffff, 0xfffffffe, 0xffffffff])
        k = K.Key(key)
        w(f'  {{ {carr(key)}, {carr(nonce)}, 0x{ctr:08x}u, {carr(k.deck)}, {carr(k.block(ctr, nonce))} }},')
    w('};\n')

    # 2. one-loop schedules: every rotation set exercised in all 20 rounds (kernel level)
    key = bytes(range(32)); nonce = bytes.fromhex('000000090000004a00000000')
    w('/* kci_core with loop s forced into all 20 rounds; stack constants, key 00..1f, ctr 1, RFC nonce */')
    w('static const uint8_t kat_single_loop[8][64] = {')
    for s in range(8):
        out = struct.pack('<16I', *K.core(K.STACK_CONST, key, 1, nonce, [K.LOOP_ROT[s]] * 20,
                                          [K.rc(r, s) for r in range(20)]))
        w('  ' + carr(out) + ',')
    w('};\n')

    # 2b. reduced rounds 1..8 with the deck of key 00..1f (tests the non-multiple-of-4 tail path)
    k = K.Key(key)
    w('/* kci_core with the first R rounds of the deck of key 00..1f, R = 1..8; stack constants, ctr 1, RFC nonce */')
    w('static const uint8_t kat_reduced[8][64] = {')
    for R in range(1, 9):
        out = struct.pack('<16I', *K.core(K.STACK_CONST, key, 1, nonce, k.rots[:R], k.rcs[:R]))
        w('  ' + carr(out) + ',')
    w('};\n')

    # 3. stream vector across block boundaries (300 bytes, ctr0 = 1)
    key = bytes(range(0x80, 0xa0)); nonce = bytes(range(0x07, 0x13)); n = 300
    pt = bytes((i * 7 + 3) & 0xff for i in range(n))
    ct = bytes(a ^ b for a, b in zip(pt, stream(K.Key(key).block, 1, nonce, n)))
    w(f'static const uint8_t kat_stream_key[32] = {carr(key)};')
    w(f'static const uint8_t kat_stream_nonce[12] = {carr(nonce)};')
    w(f'#define KAT_STREAM_LEN {n}')
    w(f'static const uint8_t kat_stream_ct[{n}] = {carr(ct)};\n')

    # 4. ChaCha-mode kernel cross-check: RFC 8439 2.3.2 block + 300-byte keystream checked against OpenSSL
    rfc_key = bytes(range(32)); rfc_nonce = bytes.fromhex('000000090000004a00000000')
    rfc = chacha_block(rfc_key, 1, rfc_nonce)
    assert rfc.hex().startswith('10f1e7e4d13b5915500fdd1fa32071c4'), 'RFC 8439 2.3.2 mismatch'
    w(f'static const uint8_t kat_rfc8439_block[64] = {carr(rfc)}; /* RFC 8439 2.3.2 */')
    ks = stream(lambda c, nn: chacha_block(key, c, nn), 1, nonce, n)
    checked = 'not checked (openssl missing)'
    if shutil.which('openssl'):
        iv = struct.pack('<I', 1) + nonce
        o = subprocess.run(['openssl', 'enc', '-chacha20', '-K', key.hex(), '-iv', iv.hex()],
                           input=bytes(n), capture_output=True, check=True).stdout
        assert o == ks, 'ChaCha-mode keystream disagrees with OpenSSL'
        checked = 'matches OpenSSL chacha20'
    w(f'/* ChaCha-mode keystream, key kat_stream_key, nonce kat_stream_nonce, ctr 1: {checked} */')
    w(f'static const uint8_t kat_chacha_stream[{n}] = {carr(ks)};\n')

    # 5. Poly1305: RFC 8439 2.5.2 + edge cases, each checked against OpenSSL's POLY1305 MAC when available
    def ossl_poly(key, msg):
        if not shutil.which('openssl'):
            return None
        o = subprocess.run(['openssl', 'mac', '-macopt', 'hexkey:' + key.hex(), 'POLY1305'],
                           input=msg, capture_output=True, check=True).stdout
        return bytes.fromhex(o.decode().strip())
    prnd = random.Random(1305)
    pool_ff = b'\xff' * 256
    pool_rn = bytes(prnd.getrandbits(8) for _ in range(256))
    pkeys = [bytes.fromhex('85d6be7857556d337f4452fe42d506a80103808afb0db2fd4abff6af4149f51b'),
             b'\xff' * 32,                                   # r clamps to its maximum, s all ones
             bytes(16) + bytes(prnd.getrandbits(8) for _ in range(16)),   # r = 0: tag = s
             b'\xff' * 16 + bytes(16),                       # max r, s = 0
             bytes(prnd.getrandbits(8) for _ in range(32))]
    w(f'static const uint8_t kat_pool_ff[256] = {carr(pool_ff)};')
    w(f'static const uint8_t kat_pool_rn[256] = {carr(pool_rn)};')
    w('static const uint8_t kat_poly_keys[][32] = {' + ','.join(carr(k_) for k_ in pkeys) + '};')
    w('struct kat_poly { uint8_t key; uint8_t pool; uint16_t len; uint8_t tag[16]; };  /* pool 0 = ff, 1 = random */')
    w('static const struct kat_poly kat_polys[] = {')
    n_ossl = 0
    for ki, pk in enumerate(pkeys):
        for li, ln in enumerate([0, 1, 15, 16, 17, 31, 32, 33, 63, 64, 65, 100, 255, 256]):
            for pool_i, pool in enumerate((pool_ff, pool_rn)):
                msg = pool[:ln]; tag = K.poly1305(pk, msg)
                o = ossl_poly(pk, msg)
                if o is not None:
                    assert o == tag, f'Poly1305 disagrees with OpenSSL: key {ki} len {ln} pool {pool_i}'; n_ossl += 1
                w(f'  {{ {ki}, {pool_i}, {ln}, {carr(tag)} }},')
    w('};')
    # 5b. final-reduction edge cases: r = 1, three full blocks summing to p + j (j = -1 .. 4), so the
    #     accumulator ends exactly at or just above p = 2^130 - 5 and the h >= p branch-free select is exercised
    special = []
    sk = b'\x01' + bytes(15) + bytes(prnd.getrandbits(8) for _ in range(16))
    for j in range(-1, 5):
        x1 = (1 << 128) - 5 + j                    # 3 * 2^128 (block markers) + x1 = 2^130 - 5 + j
        msg = x1.to_bytes(16, 'little') + bytes(32)
        tag = K.poly1305(sk, msg)
        o = ossl_poly(sk, msg)
        if o is not None:
            assert o == tag, f'Poly1305 edge case j={j} disagrees with OpenSSL'; n_ossl += 1
        special.append((msg, tag))
    w(f'static const uint8_t kat_poly_edge_key[32] = {carr(sk)};')
    w('/* message = 3 blocks with sum p + j, j = -1 .. 4 */')
    w('static const uint8_t kat_poly_edge[6][2][48] = {' + ','.join('{' + carr(m) + ',' + carr(t + bytes(32)) + '}' for m, t in special) + '};')
    rfc_msg = b'Cryptographic Forum Research Group'
    assert K.poly1305(pkeys[0], rfc_msg).hex() == 'a8061dc1305136c6c22b8baf0c0127a9', 'RFC 8439 2.5.2 mismatch'
    w(f'static const uint8_t kat_poly_rfc_msg[{len(rfc_msg)}] = {carr(rfc_msg)};')
    w(f'static const uint8_t kat_poly_rfc_tag[16] = {carr(K.poly1305(pkeys[0], rfc_msg))}; /* RFC 8439 2.5.2 */')
    w(f'/* Poly1305 vectors checked against OpenSSL: {n_ossl} */\n')

    # 6. AEAD in ChaCha mode = RFC 8439 2.8.2 (kernel + composition cross-check)
    a_pt = b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it."
    a_key = bytes(range(0x80, 0xa0)); a_nonce = bytes.fromhex('070000004041424344454647')
    a_aad = bytes.fromhex('50515253c0c1c2c3c4c5c6c7')
    a_ct, a_tag = K.aead_encrypt(lambda c, nn: chacha_block(a_key, c, nn), a_nonce, a_pt, a_aad)
    assert a_tag.hex() == '1ae10b594f09e26a7e902ecbd0600691', 'RFC 8439 2.8.2 tag mismatch'
    w(f'#define KAT_RFC_AEAD_LEN {len(a_pt)}')
    w(f'static const uint8_t kat_rfc_aead_pt[{len(a_pt)}] = {carr(a_pt)};')
    w(f'static const uint8_t kat_rfc_aead_key[32] = {carr(a_key)};')
    w(f'static const uint8_t kat_rfc_aead_nonce[12] = {carr(a_nonce)};')
    w(f'static const uint8_t kat_rfc_aead_aad[12] = {carr(a_aad)};')
    w(f'static const uint8_t kat_rfc_aead_ct[{len(a_ct)}] = {carr(a_ct)};')
    w(f'static const uint8_t kat_rfc_aead_tag[16] = {carr(a_tag)}; /* RFC 8439 2.8.2 */\n')

    # 7. KCI-20 AEAD vectors (pt and aad taken from the random pool)
    arnd = random.Random(8439)
    w('struct kat_aead { uint8_t key[32]; uint8_t nonce[12]; uint16_t aad_len; uint16_t len; uint16_t ct_off; uint8_t tag[16]; };')
    cts = b''; rows = []
    for aad_len in (0, 12, 17):
        for ln in (0, 1, 63, 64, 65, 200):
            key_ = bytes(arnd.getrandbits(8) for _ in range(32)); nonce_ = bytes(arnd.getrandbits(8) for _ in range(12))
            kk = K.Key(key_)
            ct_, tag_ = K.aead_encrypt(kk.block, nonce_, pool_rn[:ln], pool_rn[256 - aad_len:])
            rows.append(f'  {{ {carr(key_)}, {carr(nonce_)}, {aad_len}, {ln}, {len(cts)}, {carr(tag_)} }},')
            cts += ct_
    w('/* plaintext = kat_pool_rn[0..len), aad = kat_pool_rn[256 - aad_len .. 256) */')
    w('static const struct kat_aead kat_aeads[] = {'); [w(r) for r in rows]; w('};')
    w(f'static const uint8_t kat_aead_cts[{max(len(cts),1)}] = {carr(cts or bytes(1))};\n')

    # 8. SHA-256 / HMAC-SHA256 / PBKDF2-HMAC-SHA256, oracle = Python hashlib (+ FIPS / RFC values asserted)
    fips = {b'': 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855',
            b'abc': 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad',
            b'abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq':
                '248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1'}
    for m_, h_ in fips.items():
        assert hashlib.sha256(m_).hexdigest() == h_, 'FIPS 180-4 mismatch'
    assert hashlib.sha256(b'a' * 1000000).hexdigest() == 'cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0'
    w('/* SHA-256 of kat_pool_rn[0..len) repeated to 1000 bytes; lengths cover every padding boundary */')
    shapool = (pool_rn * 4)[:1000]
    w(f'static const uint8_t kat_sha_pool[1000] = {carr(shapool)};')
    lens = list(range(0, 130)) + [191, 192, 193, 255, 256, 257, 1000]
    w('struct kat_sha { uint16_t len; uint8_t md[32]; };')
    w('static const struct kat_sha kat_shas[] = {' + ','.join(f'{{{n},{carr(hashlib.sha256(shapool[:n]).digest())}}}' for n in lens) + '};')
    w('static const uint8_t kat_sha_abc[32] = ' + carr(bytes.fromhex(fips[b'abc'])) + '; /* FIPS 180-4 */')
    w('static const uint8_t kat_sha_448[32] = ' + carr(bytes.fromhex(fips[b'abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq'])) + '; /* FIPS 180-4 */')
    w('static const uint8_t kat_sha_million_a[32] = ' + carr(hashlib.sha256(b'a' * 1000000).digest()) + '; /* FIPS 180-4 */\n')

    hm = [(b'\x0b' * 20, b'Hi There'),
          (b'Jefe', b'what do ya want for nothing?'),
          (b'\xaa' * 20, b'\xdd' * 50),
          (bytes(range(1, 26)), b'\xcd' * 50),
          (b'\xaa' * 131, b'Test Using Larger Than Block-Size Key - Hash Key First'),
          (b'\xaa' * 131, b'This is a test using a larger than block-size key and a larger than block-size data. '
                          b'The key needs to be hashed before being used by the HMAC algorithm.'),
          (b'', b'empty key'), (pool_rn[:63], b'k63'), (pool_rn[:64], b'k64'), (pool_rn[:65], b'k65')]
    assert hmac.new(b'Jefe', b'what do ya want for nothing?', 'sha256').hexdigest() == \
        '5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843', 'RFC 4231 case 2 mismatch'
    w('/* HMAC-SHA256: RFC 4231 cases 1, 2, 3, 4, 6, 7, then key lengths 0 / 63 / 64 / 65 */')
    w('struct kat_hmac { uint8_t key[131]; uint8_t key_len; uint8_t msg[160]; uint8_t msg_len; uint8_t mac[32]; };')
    w('static const struct kat_hmac kat_hmacs[] = {')
    for k_, m_ in hm:
        w(f'  {{ {carr(k_ or bytes(1))}, {len(k_)}, {carr(m_)}, {len(m_)}, {carr(hmac.new(k_, m_, "sha256").digest())} }},')
    w('};\n')

    pb = [(b'passwd', b'salt', 1, 64), (b'Password', b'NaCl', 80000, 64), (b'password', b'salt', 2, 32),
          (b'password', b'salt', 4096, 40), (b'', b'salt', 3, 32), (pool_rn[:100], pool_rn[100:140], 5, 97)]
    assert hashlib.pbkdf2_hmac('sha256', b'passwd', b'salt', 1, 64).hex().startswith('55ac046e56e3089fec1691c22544b605'), 'RFC 7914 #1'
    assert hashlib.pbkdf2_hmac('sha256', b'Password', b'NaCl', 80000, 64).hex().startswith('4ddcd8f60b98be21830cee5ef22701f9'), 'RFC 7914 #2'
    w('/* PBKDF2-HMAC-SHA256: RFC 7914 section 11 (#1, #2), then extra cases incl. a 100-byte password and a 97-byte output */')
    w('struct kat_pbkdf2 { uint8_t pw[100]; uint8_t pw_len; uint8_t salt[40]; uint8_t salt_len; uint32_t iter; uint8_t dk_len; uint8_t dk[97]; };')
    w('static const struct kat_pbkdf2 kat_pbkdf2s[] = {')
    for pw_, sa_, it_, dl_ in pb:
        dk_ = hashlib.pbkdf2_hmac('sha256', pw_, sa_, it_, dl_)
        w(f'  {{ {carr(pw_ or bytes(1))}, {len(pw_)}, {carr(sa_)}, {len(sa_)}, {it_}u, {dl_}, {carr(dk_)} }},')
    w('};')
    kdf_pw = b'correct horse battery staple'; kdf_salt = bytes(range(16))
    w(f'static const uint8_t kat_kdf_pw[{len(kdf_pw)}] = {carr(kdf_pw)};')
    w(f'static const uint8_t kat_kdf_salt[16] = {carr(kdf_salt)};')
    w(f'static const uint8_t kat_kdf_key_default[32] = {carr(hashlib.pbkdf2_hmac("sha256", kdf_pw, kdf_salt, 600000, 32))}; /* 600 000 iterations */\n')

    w('#endif')
    with open(OUT, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote', os.path.normpath(OUT), '| ChaCha-mode stream:', checked)

if __name__ == '__main__':
    main()
