"""Generate tests/kat_vectors.h from the Python reference sketch (tools/kci_ref.py).

These are *provisional* vectors: the C portable path must agree with them (two independent implementations).
The ChaCha-mode stream vector is also checked against OpenSSL's chacha20 when `openssl` is on PATH.

Run from the repo root:  python3 -I tools/gen_vectors.py
"""
import os, random, shutil, struct, subprocess, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
import kci_ref as K  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tests', 'kat_vectors.h')

def carr(b):
    return '{' + ','.join(f'0x{x:02x}' for x in b) + '}'

def stream(key_obj_block, ctr0, nonce, n):
    ks = b''; c = ctr0
    while len(ks) < n:
        ks += key_obj_block(c, nonce); c += 1
    return ks[:n]

def chacha_block(key, ctr, nonce):
    return struct.pack('<16I', *K.core(K.CHACHA_CONST, key, ctr, nonce, [(16, 12, 8, 7)] * 20, [0] * 20))

def main():
    L = []
    w = L.append
    w('/* GENERATED by tools/gen_vectors.py from tools/kci_ref.py (spec v0.2). Do not edit by hand. */')
    w('#ifndef KCI_KAT_VECTORS_H\n#define KCI_KAT_VECTORS_H\n#include <stdint.h>\n')

    # tables (C must match the Python FROZEN / PACKED)
    w('static const uint8_t kat_loop_rot[8][4] = {' + ','.join('{' + ','.join(map(str, p)) + '}' for p in K.LOOP_ROT) + '};')
    w('static const uint32_t kat_loop_packed[8] = {' + ','.join(f'0x{p:08x}u' for p in K.PACKED) + '};\n')

    # 1. block KATs with their decks: fixed key, then deterministic pseudo-random keys
    rnd = random.Random(20261127)
    keys = [bytes(range(32))] + [bytes(rnd.getrandbits(8) for _ in range(32)) for _ in range(5)]
    w('struct kat_block { uint8_t key[32]; uint8_t nonce[12]; uint32_t ctr; uint8_t deck[20]; uint8_t out[64]; };')
    w('static const struct kat_block kat_blocks[] = {')
    for i, key in enumerate(keys):
        nonce = bytes.fromhex('000000090000004a00000000') if i == 0 else bytes(rnd.getrandbits(8) for _ in range(12))
        ctr = 1 if i == 0 else rnd.choice([0, 1, 2, 0x7fffffff, 0xfffffffe, 0xffffffff])
        k = K.Key(key)
        w(f'  {{ {carr(key)}, {carr(nonce)}, 0x{ctr:08x}u, {carr(k.deck)}, {carr(k.block(ctr, nonce))} }},')
    w('};\n')

    # 2. one-loop schedules: every rotation set exercised in all 20 rounds (kernel level)
    key = bytes(range(32)); nonce = bytes.fromhex('000000090000004a00000000')
    w('/* kci_core with loop s forced into all 20 rounds; stack constants, key 00..1f, ctr 1, RFC nonce */')
    w('static const uint8_t kat_single_loop[8][64] = {')
    for s in range(8):
        out = struct.pack('<16I', *K.core(K.STACK_CONST, key, 1, nonce, [K.LOOP_ROT[s]] * 20,
                                          [K.rc(r, s) for r in range(20)]))
        w('  ' + carr(out) + ',')
    w('};\n')

    # 2b. reduced rounds 1..8 with the deck of key 00..1f (tests the non-multiple-of-4 tail path)
    k = K.Key(key)
    w('/* kci_core with the first R rounds of the deck of key 00..1f, R = 1..8; stack constants, ctr 1, RFC nonce */')
    w('static const uint8_t kat_reduced[8][64] = {')
    for R in range(1, 9):
        out = struct.pack('<16I', *K.core(K.STACK_CONST, key, 1, nonce, k.rots[:R], k.rcs[:R]))
        w('  ' + carr(out) + ',')
    w('};\n')

    # 3. stream vector across block boundaries (300 bytes, ctr0 = 1)
    key = bytes(range(0x80, 0xa0)); nonce = bytes(range(0x07, 0x13)); n = 300
    pt = bytes((i * 7 + 3) & 0xff for i in range(n))
    ct = bytes(a ^ b for a, b in zip(pt, stream(K.Key(key).block, 1, nonce, n)))
    w(f'static const uint8_t kat_stream_key[32] = {carr(key)};')
    w(f'static const uint8_t kat_stream_nonce[12] = {carr(nonce)};')
    w(f'#define KAT_STREAM_LEN {n}')
    w(f'static const uint8_t kat_stream_ct[{n}] = {carr(ct)};\n')

    # 4. ChaCha-mode kernel cross-check: RFC 8439 2.3.2 block + 300-byte keystream checked against OpenSSL
    rfc_key = bytes(range(32)); rfc_nonce = bytes.fromhex('000000090000004a00000000')
    rfc = chacha_block(rfc_key, 1, rfc_nonce)
    assert rfc.hex().startswith('10f1e7e4d13b5915500fdd1fa32071c4'), 'RFC 8439 2.3.2 mismatch'
    w(f'static const uint8_t kat_rfc8439_block[64] = {carr(rfc)}; /* RFC 8439 2.3.2 */')
    ks = stream(lambda c, nn: chacha_block(key, c, nn), 1, nonce, n)
    checked = 'not checked (openssl missing)'
    if shutil.which('openssl'):
        iv = struct.pack('<I', 1) + nonce
        o = subprocess.run(['openssl', 'enc', '-chacha20', '-K', key.hex(), '-iv', iv.hex()],
                           input=bytes(n), capture_output=True, check=True).stdout
        assert o == ks, 'ChaCha-mode keystream disagrees with OpenSSL'
        checked = 'matches OpenSSL chacha20'
    w(f'/* ChaCha-mode keystream, key kat_stream_key, nonce kat_stream_nonce, ctr 1: {checked} */')
    w(f'static const uint8_t kat_chacha_stream[{n}] = {carr(ks)};\n')

    w('#endif')
    with open(OUT, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote', os.path.normpath(OUT), '| ChaCha-mode stream:', checked)

if __name__ == '__main__':
    main()
